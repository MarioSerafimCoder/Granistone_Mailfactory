import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createCampaign } from '../campaigns/model';
import { createSection } from '../blocks/registry';
import { defaultBrand } from '../data/brand';
import { prepareBrand, prepareCampaignImages } from '../lib/prepare-email';
import { hasLocalImages, hostLocalImages, mergeHostedImages } from '../lib/workspace-images';

const origin = 'https://studio.example.com';
const path = `/assets/${'a'.repeat(64)}`;
test('preparation fills localized image descriptions and resolves known hosted resources without changing the composition', () => {
  const section = createSection('twoProducts');
  const campaign = createCampaign({ sections: [section] });
  campaign.content.pt.heroImage = path;
  campaign.content.en.heroImage = origin + path;
  campaign.content.en.heroAlt = 'My own description';
  section.content.pt.image = path;
  section.content.pt.alt = '';
  section.content.en.image2 = path;
  section.content.en.alt2 = '';
  section.content.en.title2 = 'Second stone';
  section.settings.background = { kind: 'image', image: path, fallback: '#FFFFFF', overlay: 0, size: 'cover', position: 'center' };
  const before = structuredClone(campaign);
  const prepared = prepareCampaignImages(campaign, origin);
  assert.equal(prepared.content.pt.heroImage, origin + path);
  assert.match(prepared.content.pt.heroAlt, /^Imagem principal/);
  assert.equal(prepared.content.en.heroAlt, 'My own description');
  assert.equal(prepared.sections![0].content.en.alt2, 'Image · Second stone');
  assert.equal(prepared.sections![0].content.pt.image, origin + path);
  assert.equal(prepared.sections![0].settings.background.kind === 'image' && prepared.sections![0].settings.background.image, origin + path);
  assert.equal(prepared.sections![0].id, section.id);
  assert.deepEqual(prepared.blocks, before.blocks);
  assert.deepEqual(campaign, before);
  assert.deepEqual(prepareCampaignImages(prepared, origin), prepared);
  assert.equal(prepared.content.es.heroImage, '', 'missing photos must not be invented or copied from other languages');
  assert.equal(prepareBrand(defaultBrand, origin).assetBaseUrl, origin);
  assert.equal(prepareBrand({ ...defaultBrand, logoUrl: '/brand/granistone-logo.png' }, origin).logoUrl, origin + '/brand/granistone-logo.png');
  assert.equal(prepareBrand(defaultBrand, 'http://localhost:3000').assetBaseUrl, '');
});

test('hosting discovers nested backgrounds, deduplicates images and rebases uploads without losing concurrent edits', async () => {
  const a = createSection('banner'), b = createSection('banner');
  const uri = 'data:image/png;base64,AAAA';
  a.content.pt.image = uri; a.content.en.image = uri;
  b.content.pt.image = uri;
  a.settings.background = { kind: 'image', image: uri, fallback: '#FFFFFF', overlay: 0, size: 'cover', position: 'center' };
  const source = createCampaign({ sections: [a, b] });
  let uploads = 0;
  const hosted = await hostLocalImages(source, async () => { uploads++; return { url: origin + path }; });
  assert.equal(uploads, 1); assert.equal(hasLocalImages(source), true); assert.equal(hasLocalImages(hosted), false);
  const current = structuredClone(source);
  current.title = 'Edited while uploading';
  current.sections = [current.sections![0]];
  current.sections[0].content.pt.image = 'https://example.com/replacement.jpg';
  current.sections[0].content.en.title = 'English edited';
  const merged = mergeHostedImages(current, source, hosted);
  assert.equal(merged.title, current.title);
  assert.equal(merged.sections!.length, 1);
  assert.equal(merged.sections![0].content.pt.image, 'https://example.com/replacement.jpg');
  assert.equal(merged.sections![0].content.en.image, origin + path);
  assert.equal(merged.sections![0].content.en.title, 'English edited');
  assert.equal(hasLocalImages(merged), false);
});
